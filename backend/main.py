@app.post("/products", status_code=201)
def create_product(
    payload: ProductCreate,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    if current_user.role != "farmer":
        raise HTTPException(403, "Only farmer accounts can create product listings")
    if not payload.title.strip() or payload.price_xaf <= 0 or payload.quantity_available <= 0:
        raise HTTPException(400, "Product title, price, and quantity must be positive")
    category = LISTING_CATEGORY_MAP.get(payload.category.strip().lower())
    if not category:
        raise HTTPException(400, "Choose one of: Vegetables, Tubers, Fruits, Spices, or Grains")
    listing = ProduceListing(
        id=str(uuid.uuid4()),
        farmer_id=current_user.id,
        title=payload.title.strip(),
        crop_type=payload.title.strip(),
        category=category,
        price_xaf=payload.price_xaf,
        unit=payload.unit.strip(),
        quantity_available=payload.quantity_available,
        region=(current_user.location or "").split(",")[0].strip() or "Unknown",
        image_url=payload.image_url,
        description=payload.description.strip(),
        quality_grade="Standard",
        size="Medium",
        is_fresh=True,
        verification_status="pending",
    )
    try:
        db.add(listing)
        db.commit()
        db.refresh(listing)
        return serialize_model(listing)
    except SQLAlchemyError as exc:
        db.rollback()
        raise HTTPException(500, "Unable to save this product listing. Please try again.") from exc


