# Forecast artifacts are generated by model/production_pipeline.py.  They are
# deliberately read from disk rather than copied into PricePrediction: the
# latter is an application table, while these files retain the model interval,
# reliability score, provenance, and explanation needed by the forecast UI.
PROJECT_DIR = Path(__file__).resolve().parent.parent
MODEL_DIR = PROJECT_DIR / "model"
MODEL_DATA_DIR = MODEL_DIR / "data"
MODEL_FORECAST_DIR = MODEL_DIR / "production_output" / "forecasts"
MODEL_ARTIFACT_DIR = MODEL_DIR / "production_output" / "models"


def _available_model_crops() -> dict[str, str]:
    """Return case-insensitive crop lookup keys mapped to safe file stems."""
    return {path.stem.lower(): path.stem for path in MODEL_DATA_DIR.glob("*.csv")}


def _forecast_rows(path: Path) -> list[dict]:
    if not path.is_file():
        raise HTTPException(
            status_code=503,
            detail="Forecast artifacts are unavailable. Run model/production_pipeline.py first.",
        )
    with path.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    number_fields = {
        "horizon_months", "predicted_price", "lower_80", "upper_80",
        "confidence_score_percent", "interval_confidence_percent", "days_covered",
        "year", "months_covered", "avg_predicted_price", "avg_lower_80",
        "avg_upper_80", "min_predicted_price", "max_predicted_price",
    }
    for row in rows:
        for field in number_fields.intersection(row):
            value = row[field]
            if value == "":
                row[field] = None
            elif field in {"horizon_months", "days_covered", "year", "months_covered", "interval_confidence_percent"}:
                row[field] = int(float(value))
            else:
                row[field] = float(value)
        if "partial_year" in row:
            row["partial_year"] = row["partial_year"].strip().lower() == "true"
    return rows


def _model_summary(stem: str) -> dict:
    path = MODEL_ARTIFACT_DIR / f"{stem}_model.json"
    if not path.is_file():
        return {}
    with path.open(encoding="utf-8") as handle:
        artifact = json.load(handle)
    return {
        "summary": artifact.get("summary", {}),
        "view_notes": artifact.get("view_notes", {}),
    }


@app.get("/forecast/crops")
def get_forecast_crops():
    """List crops with generated model forecasts and the supported views."""
    crops = []
    for stem in sorted(set(_available_model_crops().values())):
        summary = _model_summary(stem).get("summary", {})
        crops.append(
            {
                "crop": stem,
                "available_frequencies": ["daily", "weekly", "monthly", "yearly"],
                "training_end": summary.get("training_end"),
                "test_wape": summary.get("test_wape"),
            }
        )
    return crops


@app.get("/forecast/{crop_name}")
def get_model_forecast(
    crop_name: str,
    frequency: Literal["daily", "weekly", "monthly", "yearly"] = Query(default="monthly"),
    include_history: bool = Query(default=False),
):
    """Serve a model forecast and, optionally, its observed monthly history.

    Daily and weekly response rows include `source_frequency` so clients can
    clearly disclose that they are display views derived from the monthly
    model, not independently validated high-frequency forecasts.
    """
    crops = _available_model_crops()
    stem = crops.get(crop_name.strip().lower())
    if stem is None:
        raise HTTPException(status_code=404, detail=f"No model data found for crop '{crop_name}'.")
    filename = f"{stem}_{frequency}_future.csv" if frequency != "monthly" else f"{stem}_future.csv"
    summary = _model_summary(stem)
    response = {
        "commodity": stem,
        "frequency": frequency,
        "data_scope": "Monthly commodity series; no city-level data is currently available.",
        "forecast": _forecast_rows(MODEL_FORECAST_DIR / filename),
        "model": summary.get("summary", {}),
        "view_notes": summary.get("view_notes", {}),
    }
    if include_history:
        with (MODEL_DATA_DIR / f"{stem}.csv").open(newline="", encoding="utf-8") as handle:
            response["history"] = [
                {"date": row["date"], "price": float(row["value"]), "is_predicted": False}
                for row in csv.DictReader(handle)
            ]
    return response


class ForecastAlertCreate(BaseModel):
    user_id: str
    crop_name: str
    threshold_price: float
    direction: Literal["above", "below"]
    frequency: Literal["daily", "weekly", "monthly"] = "daily"


def _forecast_filename(stem: str, frequency: str) -> str:
    return f"{stem}_future.csv" if frequency == "monthly" else f"{stem}_{frequency}_future.csv"


def _threshold_crossing(alert: ForecastPriceAlert) -> dict | None:
    """Return the first future model row satisfying an active alert."""
    rows = _forecast_rows(MODEL_FORECAST_DIR / _forecast_filename(alert.crop_name, alert.frequency))
    threshold = float(alert.threshold_price)
    for row in rows:
        price = float(row["predicted_price"])
        if (alert.direction == "above" and price >= threshold) or (
            alert.direction == "below" and price <= threshold
        ):
            return row
    return None


def _trigger_alert(alert: ForecastPriceAlert, crossing: dict, db: Session) -> None:
    alert.active = False
    alert.triggered_at = datetime.now(timezone.utc)
    comparison = "reached or exceeded" if alert.direction == "above" else "reached or fell below"
    # Some existing frontend sessions identify users by phone rather than the
    # database UUID. Keep the threshold alert itself, and create an in-app
    # notification only once we have a matching persisted user record.
    if db.query(User).filter(User.id == alert.user_id).first() is not None:
        db.add(
            PriceAlertNotification(
            id=str(uuid.uuid4()),
            user_id=alert.user_id,
            title="Forecast price alert",
            message=(
                f"{alert.crop_name} is forecast at {float(crossing['predicted_price']):,.0f} FCFA "
                f"on {crossing.get('date', crossing.get('week_start'))}; it has {comparison} "
                f"your {float(alert.threshold_price):,.0f} FCFA threshold."
            ),
            crop_type=alert.crop_name,
            type="price_surge" if alert.direction == "above" else "price_drop",
            read=False,
            )
        )


@app.post("/forecast-alerts", status_code=201)
def create_forecast_alert(payload: ForecastAlertCreate, db: Session = Depends(get_db)):
    crops = _available_model_crops()
    stem = crops.get(payload.crop_name.strip().lower())
    if stem is None:
        raise HTTPException(status_code=404, detail=f"No model data found for crop '{payload.crop_name}'.")
    if payload.threshold_price <= 0:
        raise HTTPException(status_code=422, detail="threshold_price must be positive.")
    alert = ForecastPriceAlert(
        id=str(uuid.uuid4()),
        user_id=payload.user_id,
        crop_name=stem,
        threshold_price=payload.threshold_price,
        direction=payload.direction,
        frequency=payload.frequency,
        active=True,
    )
    crossing = _threshold_crossing(alert)
    if crossing is not None:
        _trigger_alert(alert, crossing, db)
    db.add(alert)
    db.commit()
    return {
        "alert_id": alert.id,
        "active": alert.active,
        "triggered": crossing is not None,
        "crossing": crossing,
    }


