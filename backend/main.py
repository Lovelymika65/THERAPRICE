def send_otp_email(to_email: str, otp_code: str):
    sender = os.getenv("EMAIL_ADDRESS")
    password = os.getenv("EMAIL_APP_PASSWORD")

    msg = MIMEText(f"Your Theraprice verification code is: {otp_code}\n\nThis code expires in 10 minutes.")
    msg["Subject"] = "Your Theraprice verification code"
    msg["From"] = sender
    msg["To"] = to_email

    with smtplib.SMTP("smtp.gmail.com", 587) as server:
        server.starttls()
        server.login(sender, password)
        server.send_message(msg)    


@app.post("/send-otp")
def send_otp(payload: SendOtpRequest, db: Session = Depends(get_db)):
    pending = db.query(PendingRegistration).filter(PendingRegistration.phone == payload.phone).first()
    if not pending:
        raise HTTPException(status_code=404, detail="No pending registration found")

    code = str(random.randint(100000, 999999))  # 6-digit code
    pending.otp_code = code
    pending.otp_expires_at = datetime.now(timezone.utc) + timedelta(minutes=10)
    db.commit()

    if payload.channel == "sms":
        # An SMS gateway is not configured for this project yet. Do not claim
        # that a code was sent when it cannot be delivered.
        raise HTTPException(status_code=503, detail="SMS verification is not configured. Select email verification.")

    try:
        send_otp_email(pending.email, code)
    except (OSError, smtplib.SMTPException) as exc:
        raise HTTPException(status_code=503, detail="OTP email could not be sent. Check EMAIL_ADDRESS and EMAIL_APP_PASSWORD.") from exc

    return {"message": "OTP sent"}


@app.post("/verify-otp")
def verify_otp(payload: VerifyOtpRequest, db: Session = Depends(get_db)):
    pending = db.query(PendingRegistration).filter(PendingRegistration.phone == payload.phone).first()
    if not pending or not pending.otp_code:
        raise HTTPException(status_code=400, detail="No OTP requested for this registration")

    if datetime.now(timezone.utc) > pending.otp_expires_at:
        raise HTTPException(status_code=400, detail="OTP expired")

    if payload.otp_code != pending.otp_code:
        raise HTTPException(status_code=400, detail="Invalid OTP")

    # OTP correct — clear it so it can't be reused
    if db.query(User).filter(User.phone == pending.phone).first():
        raise HTTPException(status_code=409, detail="Phone number was registered while verification was pending")
    user = User(
        id=str(uuid.uuid4()),
        name=pending.name,
        phone=pending.phone,
        email=pending.email,
        role=pending.role,
        location=pending.location,
        password_hash=pending.password_hash,
    )
    db.add(user)
    db.delete(pending)
    db.commit()

    token = create_access_token(data={"sub": user.id, "role": user.role})
    return {"message": "Email verified", "id": user.id, "name": user.name, "role": user.role, "access_token": token, "token_type": "bearer"}

