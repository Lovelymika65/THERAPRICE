# --- Register ---
@app.post("/register")
def register(payload: RegisterRequest, db: Session = Depends(get_db)):
    existing_phone = db.query(User).filter(User.phone == payload.phone).first()
    if existing_phone:
        raise HTTPException(status_code=400, detail="Phone number is already registered. Please log in.")
    if not payload.email:
        raise HTTPException(status_code=400, detail="An email address is required for verification")
    if db.query(User).filter(User.email == payload.email).first():
        raise HTTPException(status_code=400, detail="Email already registered")

    pending = db.query(PendingRegistration).filter(PendingRegistration.phone == payload.phone).first()
    if pending:
        pending_with_email = db.query(PendingRegistration).filter(
            PendingRegistration.email == payload.email,
            PendingRegistration.phone != payload.phone,
        ).first()
        if pending_with_email:
            raise HTTPException(status_code=400, detail="A verification is already pending for this email address")
        # This is not an account yet, so allow the person to restart an
        # unfinished registration with corrected contact details/password.
        pending.name, pending.email, pending.role, pending.location = payload.name, payload.email, payload.role, payload.location
        pending.password_hash = hash_password(payload.password)
        pending.otp_code = None
        pending.otp_expires_at = None
    else:
        if db.query(PendingRegistration).filter(PendingRegistration.email == payload.email).first():
            raise HTTPException(status_code=400, detail="A verification is already pending for this email address")
        pending = PendingRegistration(phone=payload.phone, name=payload.name, email=payload.email, password_hash=hash_password(payload.password), role=payload.role, location=payload.location)
        db.add(pending)
    db.commit()
    return {"status": "pending_verification", "phone": pending.phone, "email": pending.email}


