@app.post("/forecast-alerts/evaluate")
def evaluate_forecast_alerts(db: Session = Depends(get_db)):
    """Evaluate active alerts after a forecast refresh (safe to call from a scheduler)."""
    triggered = []
    for alert in db.query(ForecastPriceAlert).filter(ForecastPriceAlert.active.is_(True)).all():
        crossing = _threshold_crossing(alert)
        if crossing is not None:
            _trigger_alert(alert, crossing, db)
            triggered.append({"alert_id": alert.id, "crossing": crossing})
    db.commit()
    return {"triggered": triggered, "count": len(triggered)}


